/**
 * Advanced SubStation Alpha rendering.
 *
 * SRT cannot express the things a bilingual subtitle actually needs: separate
 * colours for source and translation, independent outline, and a real gap
 * between the two lines. ASS can, so it is the styled output format.
 */

import { DEFAULT_ASS_STYLE } from "./catalog.ts";
import type { AssStyleOptions, BilingualCue, Cue } from "./types.ts";

/** `#RRGGBB` → ASS `&HAABBGGRR`. */
export function toAssColor(hex: string, alpha = 0): string {
  const normalised = hex.replace("#", "").trim();
  const full =
    normalised.length === 3
      ? normalised
          .split("")
          .map((c) => c + c)
          .join("")
      : normalised.padEnd(6, "0").slice(0, 6);
  const r = Number.parseInt(full.slice(0, 2), 16) || 0;
  const g = Number.parseInt(full.slice(2, 4), 16) || 0;
  const b = Number.parseInt(full.slice(4, 6), 16) || 0;
  const a = Math.max(0, Math.min(255, Math.round(alpha)));
  const hex2 = (n: number): string => n.toString(16).padStart(2, "0").toUpperCase();
  return `&H${hex2(a)}${hex2(b)}${hex2(g)}${hex2(r)}`;
}

/** `H:MM:SS.cc` — ASS uses centiseconds, not milliseconds. */
export function formatAssTime(ms: number): string {
  const clamped = Math.max(0, Math.round(ms));
  const hours = Math.floor(clamped / 3_600_000);
  const minutes = Math.floor((clamped % 3_600_000) / 60_000);
  const seconds = Math.floor((clamped % 60_000) / 1000);
  const centis = Math.floor((clamped % 1000) / 10);
  const pad = (n: number): string => String(n).padStart(2, "0");
  return `${hours}:${pad(minutes)}:${pad(seconds)}.${pad(centis)}`;
}

/** Escape the characters ASS treats as override-block syntax. */
export function escapeAssText(text: string): string {
  return text
    .replace(/\{/g, "\\{")
    .replace(/\}/g, "\\}")
    .replace(/\r?\n/g, "\\N");
}

export interface AssRenderOptions {
  playResX?: number;
  playResY?: number;
  style?: Partial<AssStyleOptions>;
}

/** Render bilingual cues as a complete .ass document. */
export function renderAss(
  cues: readonly BilingualCue[],
  options: AssRenderOptions = {},
): string {
  const style: AssStyleOptions = { ...DEFAULT_ASS_STYLE, ...options.style };
  const playResX = options.playResX ?? 1920;
  const playResY = options.playResY ?? 1080;

  const originalSize = Math.round(style.fontSize);
  const translationSize = Math.round(style.fontSize * 0.82);

  // Two styles: the source line, then the translation below it.
  const styleLine = (
    name: string,
    size: number,
    colour: string,
    marginV: number,
  ): string =>
    [
      `Style: ${name}`,
      style.fontFamily,
      String(size),
      toAssColor(colour),
      toAssColor(colour),
      toAssColor(style.outlineColor),
      toAssColor(style.backColor, 128),
      style.bold ? "-1" : "0",
      "0",
      "0",
      "0",
      "100",
      "100",
      "0",
      "0",
      "1",
      String(style.outline),
      String(style.shadow),
      "2", // bottom-centre
      "60",
      "60",
      String(marginV),
      "1",
    ].join(",");

  const events = cues
    .map((cue) => {
      const source = escapeAssText(cue.text);
      const translation = cue.translation
        ? `{\\c${toAssColor(style.secondaryColor)}\\fs${translationSize}}${escapeAssText(cue.translation)}`
        : "";
      const text = translation === "" ? source : `${source}\\N${translation}`;
      return `Dialogue: 0,${formatAssTime(cue.startMs)},${formatAssTime(cue.endMs)},Src,,0,0,0,,${text}`;
    })
    .join("\n");

  return [
    "[Script Info]",
    "; Generated by DobStudio",
    "ScriptType: v4.00+",
    `PlayResX: ${playResX}`,
    `PlayResY: ${playResY}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: None",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    styleLine("Src", originalSize, style.primaryColor, style.marginV + style.lineGap + Math.round(translationSize * 0.4)),
    styleLine("Tr", translationSize, style.secondaryColor, style.marginV),
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    events,
    "",
  ].join("\n");
}

